// WCAG 2.2 contrast check straight from tokens.css. Usage: node contrast.mjs > ../contrast-report.md
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const css = readFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', 'tokens.css'), 'utf8');

function block(name) {
  const m = css.match(new RegExp(`/\\* @theme ${name} \\*/([\\s\\S]*?)/\\* @end \\*/`));
  const out = {};
  for (const [, k, v] of m[1].matchAll(/--color-([a-z0-9-]+):\s*oklch\(([^)]+)\)/g)) out[k] = v;
  return out;
}

function oklchToRgb(str) {
  const [lch, alphaPart] = str.split('/');
  let [l, c, h] = lch.trim().split(/\s+/).map((x, i) => (i === 0 && x.endsWith('%') ? parseFloat(x) / 100 : parseFloat(x)));
  const a = c * Math.cos((h * Math.PI) / 180), b = c * Math.sin((h * Math.PI) / 180);
  const l_ = l + 0.3963377774 * a + 0.2158037573 * b, m_ = l - 0.1055613458 * a - 0.0638541728 * b, s_ = l - 0.0894841775 * a - 1.291485548 * b;
  const L = l_ ** 3, M = m_ ** 3, S = s_ ** 3;
  const lin = [4.0767416621 * L - 3.3077115913 * M + 0.2309699292 * S, -1.2684380046 * L + 2.6097574011 * M - 0.3413193965 * S, -0.0041960863 * L - 0.7034186147 * M + 1.707614701 * S].map(x => Math.min(1, Math.max(0, x)));
  return { lin, alpha: alphaPart ? parseFloat(alphaPart) : 1 };
}
const toSrgb = x => (x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055);
const toLin = x => (x <= 0.04045 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4);
function composite(fg, bg) {
  if (fg.alpha >= 1) return fg.lin;
  return fg.lin.map((v, i) => toLin(toSrgb(v) * fg.alpha + toSrgb(bg.lin[i]) * (1 - fg.alpha)));
}
const lum = lin => 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2];
function ratio(fgStr, bgStr) {
  const bg = oklchToRgb(bgStr), fg = oklchToRgb(fgStr);
  const a = lum(composite(fg, bg)), b = lum(bg.lin);
  return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
}

// [foreground, background, minimum, role]
const pairs = [
  ['ink', 'paper', 4.5, 'body text on street'], ['ink', 'paper-2', 4.5, 'body text on shop floor'], ['ink-2', 'paper-2', 4.5, 'secondary text'],
  ['muted', 'paper', 4.5, 'muted labels on street'], ['muted', 'paper-2', 4.5, 'muted labels on panels'], ['muted', 'paper-3', 4.5, 'muted on recessed'],
  ['on-sign', 'sign', 4.5, 'text on yellow sign'], ['on-plate', 'plate', 4.5, 'yellow type on sign plate'], ['on-plate', 'paper', 1, 'plate vs ground (informative)'], ['on-action', 'action', 4.5, 'primary button'],
  ['on-direction', 'red', 4.5, 'buy/sell button (red)'], ['on-direction', 'blue', 4.5, 'sell button (blue, Korean)'], ['on-direction', 'green', 4.5, 'buy button (green, Global)'],
  ['red', 'paper-2', 4.5, 'red change text'], ['blue', 'paper-2', 4.5, 'blue change text'], ['green', 'paper-2', 4.5, 'green change text'],
  ['red', 'paper', 4.5, 'red text on street'], ['green', 'paper', 4.5, 'green text on street'], ['blue', 'paper', 4.5, 'blue text on street'],
  ['focus', 'paper', 3, 'focus ring (non-text)'], ['focus', 'paper-2', 3, 'focus ring on panels'], ['rule-strong', 'paper-2', 3, 'input borders (non-text)'],
];

let out = '# Contrast report (WCAG 2.2 AA)\n\nGenerated by `tools/contrast.mjs` from `tokens.css`. Text needs 4.5:1 (3:1 for 24 px+ or 18.66 px bold); non-text UI needs 3:1. Alpha colours are composited over their background.\n';
let fails = 0;
for (const theme of ['light', 'dark']) {
  const t = block(theme);
  out += `\n## ${theme}\n\n| Foreground | Background | Ratio | Needs | Result | Role |\n|---|---|---|---|---|---|\n`;
  for (const [fg, bg, min, role] of pairs) {
    if (!t[fg] || !t[bg]) { out += `| ${fg} | ${bg} | n/a | ${min} | missing | ${role} |\n`; continue; }
    const r = ratio(t[fg], t[bg]);
    const ok = r >= min; if (!ok) fails++;
    out += `| ${fg} | ${bg} | ${r.toFixed(2)} | ${min} | ${ok ? 'pass' : '**FAIL**'} | ${role} |\n`;
  }
}
out += `\n**${fails === 0 ? 'All pairs pass.' : fails + ' pair(s) fail.'}**\n`;
console.log(out);
process.exitCode = fails ? 1 : 0;
