// Serves dist/<fw>, drives headless Chrome with 4x CPU throttle, streams at several rates, types into the amount field.
import { createServer } from 'node:http';
import { readFileSync, existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, extname, dirname } from 'node:path';
import { gzipSync } from 'node:zlib';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const TOOLS = process.env.BROS_TOOLS || '/vercel/share/bros-tools';
const puppeteer = createRequire(`${TOOLS}/package.json`)('puppeteer-core');
const CHROME = process.env.CHROME_PATH || `${TOOLS}/browsers/chrome-headless-shell/linux-156.0.8078.47/chrome-headless-shell-linux64/chrome-headless-shell`;
const FWS = ['react', 'preact', 'solid'];
const RATES = [50, 200, 500];
const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css' };

const server = createServer((req, res) => {
  const [fw, ...rest] = decodeURIComponent(req.url.split('?')[0]).slice(1).split('/');
  let p = join(HERE, 'dist', fw, rest.join('/') || 'index.html');
  if (!existsSync(p) || statSync(p).isDirectory()) p = join(HERE, 'dist', fw, 'index.html');
  res.writeHead(200, { 'content-type': TYPES[extname(p)] || 'application/octet-stream' });
  res.end(readFileSync(p));
}).listen(4789);

function jsGzip(fw) {
  const dir = join(HERE, 'dist', fw, 'assets');
  return readdirSync(dir).filter(f => f.endsWith('.js')).reduce((s, f) => s + gzipSync(readFileSync(join(dir, f))).length, 0);
}
const pct = (arr, p) => { if (!arr.length) return 0; const s = [...arr].sort((a, b) => a - b); return s[Math.min(s.length - 1, Math.floor((p / 100) * s.length))]; };

const browser = await puppeteer.launch({ executablePath: CHROME, headless: true, args: ['--no-sandbox', '--disable-gpu'] });
const results = [];
for (const fw of FWS) {
  for (const rate of RATES) {
    const page = await browser.newPage();
    await page.setViewport({ width: 412, height: 915 });
    const cdp = await page.createCDPSession();
    await cdp.send('Emulation.setCPUThrottlingRate', { rate: 4 });
    await page.goto(`http://localhost:4789/${fw}/?rate=${rate}`, { waitUntil: 'load' });
    await new Promise(r => setTimeout(r, 1000));
    await page.evaluate(() => { window.__metrics.frames = []; window.__metrics.longTasks = 0; window.__metrics.events = []; });
    await cdp.send('Performance.enable');
    const before = Object.fromEntries((await cdp.send('Performance.getMetrics')).metrics.map(m => [m.name, m.value]));
    for (let i = 0; i < 12; i++) { await page.focus('#amount'); await page.keyboard.type(String(i % 10)); await new Promise(r => setTimeout(r, 450)); }
    const after = Object.fromEntries((await cdp.send('Performance.getMetrics')).metrics.map(m => [m.name, m.value]));
    const m = await page.evaluate(() => window.__metrics);
    const wall = 12 * 0.45;
    results.push({
      fw, rate,
      scriptPct: +((100 * (after.ScriptDuration - before.ScriptDuration)) / wall).toFixed(1),
      taskPct: +((100 * (after.TaskDuration - before.TaskDuration)) / wall).toFixed(1),
      longTasks: m.longTasks,
      frameP95: +pct(m.frames, 95).toFixed(1),
      inputP95: +pct(m.events, 95).toFixed(0),
      inputMax: +Math.max(0, ...m.events).toFixed(0),
    });
    await page.close();
  }
}
await browser.close();
server.close();

const sizes = Object.fromEntries(FWS.map(fw => [fw, jsGzip(fw)]));
let md = '| Framework | JS gzip | Rate (ev/s) | Main-thread busy % | Script % | Long tasks | Frame p95 (ms) | Input event p95 / max (ms) |\n|---|---|---|---|---|---|---|---|\n';
for (const r of results) md += `| ${r.fw} | ${(sizes[r.fw] / 1024).toFixed(1)} KB | ${r.rate} | ${r.taskPct} | ${r.scriptPct} | ${r.longTasks} | ${r.frameP95} | ${r.inputP95} / ${r.inputMax} |\n`;
writeFileSync(join(HERE, 'results.md'), `# Bake-off results\n\nHeadless Chrome 156, 4x CPU throttle, 412x915 viewport, 5.4 s per run while typing 12 keystrokes. Generated by measure.mjs.\n\n${md}`);
console.log(md);
